"""Generate the tables bab copies from Rich and rich-click (the versions allegro-buddy 2.7 pins):
src/render/{data,cell_tables,emoji_data}.rs and src/cli/themes.rs.

    uv run --no-project --python 3.12 --with rich==15.0.0 --with rich-click==1.9.9 tools/gen_rich_data.py
"""

import pathlib

import rich
import rich.box as rbox
from rich._emoji_codes import EMOJI
from rich._palettes import EIGHT_BIT_PALETTE, STANDARD_PALETTE
from rich._spinners import SPINNERS
from rich._unicode_data import load
from rich.color import ANSI_COLOR_NAMES
from rich.default_styles import DEFAULT_STYLES
from rich.style import Style

ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADER = '// @generated by tools/gen_rich_data.py from rich==15.0.0; do not edit.\n'


def rs_str(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\':
            out.append('\\' + ch)
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) < 32 or 0x7F <= ord(ch) < 0xA0 or 0xFE00 <= ord(ch) <= 0xFE0F or ch == '\u200d':
            out.append(f'\\u{{{ord(ch):x}}}')
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def write_cell_tables() -> None:
    """src/render/cell_tables.rs: Rich's width table of the latest Unicode version.

    Rich picks an older table when UNICODE_VERSION is set; bab ignores that variable.
    """
    from rich.cells import _SINGLE_CELL_UNICODE_RANGES

    table = load('latest')
    # cells.rs relies on these: widths 0/2 only, ASCII and Rich's
    # _SINGLE_CELL_UNICODE_RANGES 1 cell wide
    assert {width for _, _, width in table.widths} <= {0, 2}
    for low, high in _SINGLE_CELL_UNICODE_RANGES:
        for start, end, _ in table.widths:
            assert end < low or start > high or (start, end) == (0, 0), start
    out = [HEADER]
    out.append('/// Bit 31 of a range start: the range is 2 cells wide (else 0).')
    out.append('pub const WIDE: u32 = 1 << 31;\n')
    out.append(f'/// Rich `rich._unicode_data` widths of Unicode {table.unicode_version} (`load("latest")`)')
    out.append('/// as flat sorted `start, end` pairs (inclusive ranges; `start` has [`WIDE`] set for')
    out.append('/// width 2, else the width is 0); code points outside every range are 1 cell wide.')
    out.append('pub static WIDTHS: &[u32] = &[')
    for start, end, width in table.widths:
        assert end < 1 << 31
        out.append(f'    0x{start | (1 << 31 if width == 2 else 0):x}, 0x{end:x},')
    out.append('];')
    (ROOT / 'src/render/cell_tables.rs').write_text('\n'.join(out) + '\n')


THEMES_HEADER = '''//! rich-click 1.9.9 theme tables (`rich_click_theme.COLORS` / `FORMATS`), generated by
//! tools/gen_rich_data.py. Do not edit by hand.

/// A theme value as written in Python.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum TV {
    None,
    Str(&'static str),
    Bool(bool),
    Int(i64),
    Tuple(&'static [i64]),
    List(&'static [&'static str]),
}

/// `post_combine_callback`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PostCombine {
    /// `_spaced_delimiters_callback`.
    SpacedDelimiters,
    /// `_not_dim_title_callback`.
    NotDimTitle,
}

#[derive(Debug)]
pub struct ThemeDef {
    pub name: &'static str,
    pub callback: Option<PostCombine>,
    pub styles: &'static [(&'static str, TV)],
}
'''


def theme_value(v) -> str:
    if v is None:
        return 'TV::None'
    if isinstance(v, bool):
        return f'TV::Bool({str(v).lower()})'
    if isinstance(v, int):
        return f'TV::Int({v})'
    if isinstance(v, str):
        return f'TV::Str({rs_str(v)})'
    if isinstance(v, tuple):
        return f'TV::Tuple(&[{", ".join(str(i) for i in v)}])'
    if isinstance(v, list):
        return f'TV::List(&[{", ".join(rs_str(i) for i in v)}])'
    raise TypeError(v)


def theme_table(name: str, themes: dict) -> str:
    out = [f'pub static {name}: &[ThemeDef] = &[']
    for key, theme in themes.items():
        cb = theme.post_combine_callback
        cb = f'Some(PostCombine::{"SpacedDelimiters" if "spaced" in cb.__name__ else "NotDimTitle"})' if cb else 'None'
        out.append('    ThemeDef {')
        out.append(f'        name: {rs_str(key)},')
        out.append(f'        callback: {cb},')
        out.append('        styles: &[')
        for k, v in theme.styles.items():
            out.append(f'            ({rs_str(k)}, {theme_value(v)}),')
        out.append('        ],')
        out.append('    },')
    out.append('];')
    return '\n'.join(out)


def write_themes() -> None:
    """src/cli/themes.rs: rich-click's RICH_CLICK_THEME tables."""
    from rich_click.rich_click_theme import COLORS, FORMATS

    text = THEMES_HEADER + '\n' + theme_table('COLORS', COLORS) + '\n\n' + theme_table('FORMATS', FORMATS) + '\n'
    (ROOT / 'src/cli/themes.rs').write_text(text)


def main() -> None:
    table = load('latest')
    assert table.unicode_version == '17.0.0'
    lines = [HEADER]
    lines.append('/// Rich `CellTable.narrow_to_wide` (sorted).')
    lines.append('pub static NARROW_TO_WIDE: &[char] = &[')
    for ch in sorted(table.narrow_to_wide):
        assert len(ch) == 1
        lines.append(f"    '\\u{{{ord(ch):x}}}',")
    lines.append('];\n')

    lines.append('/// Rich `ANSI_COLOR_NAMES`, sorted by name.')
    lines.append('pub static ANSI_COLOR_NAMES: &[(&str, u8)] = &[')
    for name, number in sorted(ANSI_COLOR_NAMES.items()):
        lines.append(f'    ({rs_str(name)}, {number}),')
    lines.append('];\n')

    for pal_name, pal in (('STANDARD_PALETTE', STANDARD_PALETTE), ('EIGHT_BIT_PALETTE', EIGHT_BIT_PALETTE)):
        colors = pal._colors
        lines.append(f'pub static {pal_name}: [(u8, u8, u8); {len(colors)}] = [')
        for r, g, b in colors:
            lines.append(f'    ({r}, {g}, {b}),')
        lines.append('];\n')

    lines.append('/// Rich `DEFAULT_STYLES` as (name, normalized definition), sorted by name.')
    lines.append('pub static DEFAULT_STYLES: &[(&str, &str)] = &[')
    for name, style in sorted(DEFAULT_STYLES.items()):
        definition = str(style)
        assert Style.parse(definition) == style, (name, definition)
        lines.append(f'    ({rs_str(name)}, {rs_str(definition)}),')
    lines.append('];\n')

    boxes = {name: getattr(rbox, name) for name in dir(rbox) if isinstance(getattr(rbox, name), rbox.Box)}
    try:
        import rich_click.rich_box as rcbox

        for name in ('HORIZONTALS_TOP', 'HORIZONTALS_DOUBLE_TOP'):
            boxes[name] = getattr(rcbox, name)
    except ImportError:
        pass
    lines.append('/// Rich `rich.box` definitions (plus rich-click\'s HORIZONTALS_TOP/HORIZONTALS_DOUBLE_TOP).')
    lines.append('pub static BOXES: &[(&str, &str, bool)] = &[')
    for name, b in sorted(boxes.items()):
        lines.append(f'    ({rs_str(name)}, {rs_str(str(b))}, {str(b.ascii).lower()}),')
    lines.append('];\n')
    lines.append('/// Rich `PLAIN_HEADED_SUBSTITUTIONS`.')
    lines.append('pub static PLAIN_HEADED_SUBSTITUTIONS: &[(&str, &str)] = &[')
    names = {id(b): n for n, b in boxes.items()}
    for src, dst in rbox.PLAIN_HEADED_SUBSTITUTIONS.items():
        lines.append(f'    ({rs_str(names[id(src)])}, {rs_str(names[id(dst)])}),')
    lines.append('];\n')

    dots = SPINNERS['dots']
    lines.append(f'pub const DOTS_INTERVAL_MS: f64 = {float(dots["interval"])};')
    lines.append('pub static DOTS_FRAMES: &[&str] = &[')
    for frame in dots['frames']:
        lines.append(f'    {rs_str(frame)},')
    lines.append('];')
    (ROOT / 'src/render/data.rs').write_text('\n'.join(lines) + '\n')
    write_cell_tables()
    write_themes()

    emoji = [HEADER, '/// Rich `EMOJI` (name -> emoji), sorted by name.', 'pub static EMOJI: &[(&str, &str)] = &[']
    for name, value in sorted(EMOJI.items()):
        emoji.append(f'    ({rs_str(name)}, {rs_str(value)}),')
    emoji.append('];')
    (ROOT / 'src/render/emoji_data.rs').write_text('\n'.join(emoji) + '\n')
    print('rich', rich.__file__)


if __name__ == '__main__':
    main()
